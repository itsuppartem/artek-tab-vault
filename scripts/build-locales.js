const LOCALES = ['en', 'ru', 'kk', 'uk', 'be', 'sr'];

function toMessages(locale) {
  const out = {};
  for (const [key, byLocale] of Object.entries(STRINGS)) {
    const message = byLocale[locale];
    if (message == null) throw new Error(`Missing ${key} for ${locale}`);
    out[key] = { message };
  }
  return out;
}

for (const locale of LOCALES) {
  const dir = path.join(OUT, locale);
  fs.mkdirSync(dir, { recursive: true });
  const file = path.join(dir, 'messages.json');
  fs.writeFileSync(file, JSON.stringify(toMessages(locale), null, 2) + '\n');
  console.log('wrote', file);
}
